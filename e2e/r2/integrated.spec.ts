import {test,expect} from '@playwright/test';

test('R2 stored received leads and exact draft approval persist through real API and fake adapter',async({page,context,request})=>{
 const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message));
 await context.route(url=>['http:','https:'].includes(url.protocol)&&url.origin!=='http://127.0.0.1:8018',route=>route.abort());
 await page.goto('/#browser-panel');
 await expect(page.locator('#browser-applications')).toContainText('Country: RESOLVED');
 await page.getByRole('button',{name:'Answer missing questions',exact:true}).click();
 await expect(page.locator('#answer-dialog')).toBeVisible();
 await expect(page.locator('#answer-fields .answer-question')).toHaveCount(1);
 await expect(page.getByLabel('Years in unusual domain',{exact:true})).toBeVisible();
 await page.getByLabel('Years in unusual domain',{exact:true}).fill('2');
 await page.getByRole('button',{name:'Save answers and continue',exact:true}).click();
 await expect(page.locator('#answer-dialog')).not.toBeVisible();
 await page.reload();await expect(page.locator('#browser-applications')).toContainText('Years in unusual domain: RESOLVED');
 const initial=await (await request.get('/__r2/evidence')).json();
 const resolved=await (await request.get('/api/browser/applications/'+initial.application_id+'/resolutions')).json();
 expect(resolved.fields.find((f:any)=>f.label.startsWith('I certify')).state).toBe('HUMAN_ONLY');
 expect(await (await request.get('/api/browser/applications/'+initial.application_id+'/questions')).json()).toEqual([]);
 await page.getByRole('tab',{name:'Find Jobs',exact:true}).click();
 await page.getByRole('button',{name:'Review received email leads',exact:true}).click();
 await expect(page.getByRole('tab',{name:'Inbox & Drafts',exact:true})).toHaveAttribute('aria-selected','true');
 await expect(page.locator('#email-lead-list')).toContainText('R2 Frontend opportunity');
 await expect(page.locator('#email-lead-list')).toContainText('R2 Recruiter');
 await page.getByRole('button',{name:'Read conversation',exact:true}).first().click();await expect(page.getByRole('link',{name:'Open received Gmail message'})).toHaveAttribute('href',/r2-message/);
 await page.getByRole('button',{name:'Link verified opportunity'}).click();
 await expect(page.locator('.conversation-outcome')).toContainText('no duplicate created');
 await page.getByRole('button',{name:'Draft approvals',exact:true}).click();
 await page.getByRole('button',{name:'Preview Gmail draft',exact:true}).click();
 await expect(page.locator('#draft-dialog')).toBeVisible();
 await expect(page.locator('#draft-preview-body')).toContainText('ria@example.com');
 const evidence=await (await request.get('/__r2/evidence')).json();
 const packet=await (await request.get('/api/m3/packets/'+evidence.packet_id)).json();
 await expect(page.locator('#draft-preview-body pre').first()).toHaveText(packet.version_data.email_text);
 await expect(page.locator('#draft-preview-body')).toContainText(packet.version_data.subject);
 await page.getByRole('button',{name:'Approve this exact unsent draft'}).click();
 await expect(page.locator('#draft-preview-status')).toContainText('synthetic-unsent-draft');
 let saved=await (await request.get('/__r2/evidence')).json();expect(saved.adapter_calls).toBe(1);expect(saved.operations[0].gmail_draft_id).toBe('synthetic-unsent-draft');
 await page.getByRole('button',{name:'Close draft preview'}).click();await page.reload();
 await page.getByRole('button',{name:'Preview Gmail draft',exact:true}).click();
 await expect(page.locator('#draft-preview-body')).toContainText('existing_draft_or_uncertain_operation');
 await expect(page.getByRole('button',{name:'Approve this exact unsent draft'})).toBeDisabled();
 saved=await (await request.get('/__r2/evidence')).json();expect(saved.adapter_calls).toBe(1);
 await page.getByRole('button',{name:'Close draft preview'}).click();
 await request.put('/api/m3/packets/'+evidence.packet_id,{data:{subject:'Reviewed local revision',email_text:packet.version_data.email_text,email_html:packet.version_data.email_html,supporting_statement:packet.version_data.supporting_statement}});
 await page.locator('.command-subnav').getByRole('link',{name:'Draft History',exact:true}).click();await expect(page.locator('#command-draft-history-list')).toContainText('synthetic-unsent-draft');
 await request.post('/__r2/restrict-lead');await page.locator('.command-subnav').getByRole('link',{name:'Job Alerts',exact:true}).click();await page.reload();
 await expect(page.locator('#email-lead-list')).toContainText('RESTRICTED_SOURCE');
 await page.getByRole('button',{name:'Read conversation',exact:true}).first().click();await expect(page.getByRole('button',{name:'Link verified opportunity'})).toBeDisabled();
 await request.post('/api/browser/applications/'+initial.application_id+'/reported-submitted');expect(await (await request.get('/api/m3/packets')).json()).toEqual([]);
 await page.locator('.command-subnav').getByRole('link',{name:'Draft History',exact:true}).click();await expect(page.locator('#command-draft-history-list')).toContainText('synthetic-unsent-draft');
 expect(errors).toEqual([]);
});
